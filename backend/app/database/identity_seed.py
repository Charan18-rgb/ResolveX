def ensure_identity_catalog(db_path: str) -> None:
    """Idempotently seed fictional reference identities and relationships."""
    now = datetime.now(timezone.utc).isoformat()
    with get_connection(db_path) as conn:
        supplier_ids = {
            row["id"] for row in conn.execute("SELECT id FROM suppliers;").fetchall()
        }
        warehouse_ids = {
            row["id"] for row in conn.execute("SELECT id FROM warehouses;").fetchall()
        }
        for person in DEMO_PEOPLE:
            sup_id = person["supplier_id"] if person["supplier_id"] in supplier_ids else None
            wh_id = person["warehouse_id"] if person["warehouse_id"] in warehouse_ids else None
            conn.execute(
                """
                INSERT INTO people (
                    id, full_name, first_name, aliases_json, nicknames_json,
                    usernames_json, alternative_spellings_json, gender, city,
                    location_detail, occupation, org_role, category,
                    organization, department, supplier_id, warehouse_id,
                    email, phone, comm_preference, data_origin, notes,
                    created_at, updated_at
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                ON CONFLICT(id) DO UPDATE SET
                    aliases_json = excluded.aliases_json,
                    nicknames_json = excluded.nicknames_json,
                    supplier_id = COALESCE(people.supplier_id, excluded.supplier_id),
                    warehouse_id = COALESCE(people.warehouse_id, excluded.warehouse_id);
                """,
                (
                    person["id"],
                    person["full_name"],
                    person["first_name"],
                    json.dumps(person["aliases"]),
                    json.dumps(person["nicknames"]),
                    json.dumps(person["usernames"]),
                    json.dumps(person["alternative_spellings"]),
                    person["gender"],
                    person["city"],
                    person["location_detail"],
                    person["occupation"],
                    person["org_role"],
                    person["category"],
                    person["organization"],
                    person["department"],
                    sup_id,
                    wh_id,
                    person["email"],
                    person["phone"],
                    person["comm_preference"],
                    person["data_origin"],
                    person["notes"],
                    now,
                    now,
                ),
            )

        for src_id, dst_id, rel_type, shared_ctx in DEMO_RELATIONSHIPS:
            conn.execute(
                """
                INSERT OR IGNORE INTO person_relationships (
                    person_id, related_person_id, relationship_type,
                    shared_context, data_origin, created_at
                ) VALUES (?, ?, ?, ?, 'SEEDED_DEMO', ?);
                """,
                (src_id, dst_id, rel_type, shared_ctx, now),
            )
